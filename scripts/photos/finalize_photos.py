"""Turn the chosen Commons photos into the app's story photos (13 Nov 2026).

  python scripts/photos/finalize_photos.py scripts/photos/picks.json

For every scene kind in picks.json ({kind: {title, focus: [x, y], alt_en, alt_sw}}):
  1. reads the file's licence again from Commons (CC0 / public domain / CC BY / CC BY-SA only,
     never NC or ND; refuses anything else),
  2. downloads a 1280 px copy, crops it to 3:2 around `focus` (0..1 of width/height) and saves
     assets/story/<kind>.jpg at 960 x 640,
  3. writes lib/storyPhotos.ts (credits the app shows) and scripts/photos/PHOTO_CREDITS.md,
  4. draws scripts/photos/final_sheet.jpg with every crop, for a last look.
"""
import io, json, re, sys, time, urllib.parse, urllib.request
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[2]
PICKS = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
UA = "TasselStoryPhotos/1.0 (KSEF 2027 student project; github.com/maneziezra/Tassel) Python-urllib"
API = "https://commons.wikimedia.org/w/api.php"
OK_LICENCE = re.compile(r"^(cc0|public domain|pd\b|pdm|cc[- ]by(-sa)? ?[1-4]\.\d|cc[- ]by(-sa)?$)", re.I)
BAD = re.compile(r"\bnc\b|\bnd\b|non-?commercial|no-?deriv", re.I)
KINDS = ["weed", "topdress", "spray", "water", "harvest", "dry", "store", "scout", "remove", "stake", "prepare",
         "earthup", "transplant", "net", "seedtreat", "sort", "mix", "grow"]
W, H = 960, 640


def get(params):
    url = API + "?" + urllib.parse.urlencode({**params, "format": "json", "formatversion": "2"})
    for i in range(6):
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": UA}), timeout=30) as r:
                return json.load(r)
        except Exception as e:  # noqa: BLE001
            print("  retry", e, flush=True)
            time.sleep(5 * (i + 1))
    raise SystemExit("Commons did not answer")


def fetch(url):
    for i in range(6):
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": UA}), timeout=90) as r:
                return r.read()
        except Exception as e:  # noqa: BLE001
            print("  retry", e, flush=True)
            time.sleep(5 * (i + 1))
    raise SystemExit(f"could not download {url}")


def strip(html):
    return re.sub(r"\s+", " ", re.sub(r"<[^>]+>", "", html or "")).strip()


def q(s):
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'"


missing = [k for k in KINDS if k not in PICKS]
if missing:
    raise SystemExit(f"no pick for: {missing}")

out_dir = ROOT / "assets" / "story"
out_dir.mkdir(parents=True, exist_ok=True)
credits = {}
crops = []
for kind in KINDS:
    p = PICKS[kind]
    data = get(dict(action="query", titles=p["title"], prop="imageinfo", iiprop="url|size|extmetadata|mime", iiurlwidth=1280))
    page = data["query"]["pages"][0]
    ii = page["imageinfo"][0]
    md = ii["extmetadata"]
    lic = strip(md.get("LicenseShortName", {}).get("value", ""))
    terms = strip(md.get("UsageTerms", {}).get("value", ""))
    if not OK_LICENCE.search(lic) or BAD.search(lic + " " + terms):
        raise SystemExit(f"{kind}: {p['title']} has licence {lic!r}, which the app cannot use")
    artist = strip(md.get("Artist", {}).get("value", "")) or "Unknown author"
    artist = re.sub(r"\s*\(talk\)\s*$", "", artist)[:80]
    img = Image.open(io.BytesIO(fetch(ii["thumburl"] if ii.get("thumbwidth") else ii["url"]))).convert("RGB")
    w, h = img.size
    if w / h > W / H:            # too wide: keep the full height
        cw, ch = round(h * W / H), h
    else:                        # too tall: keep the full width
        cw, ch = w, round(w * H / W)
    fx, fy = p.get("focus", [0.5, 0.5])
    left = min(max(0, round(fx * w - cw / 2)), w - cw)
    top = min(max(0, round(fy * h - ch / 2)), h - ch)
    crop = img.crop((left, top, left + cw, top + ch)).resize((W, H), Image.LANCZOS)
    crop.save(out_dir / f"{kind}.jpg", "JPEG", quality=74, optimize=True, progressive=True)
    crops.append((kind, crop))
    credits[kind] = dict(title=page["title"][5:], author=artist, licence=lic,
                         licence_url=strip(md.get("LicenseUrl", {}).get("value", "")),
                         source=ii["descriptionurl"], alt_en=p["alt_en"], alt_sw=p["alt_sw"],
                         restrictions=strip(md.get("Restrictions", {}).get("value", "")))
    print(kind, lic, artist, (out_dir / f"{kind}.jpg").stat().st_size // 1024, "KB", flush=True)
    time.sleep(1)

lines = ["// GENERATED by scripts/photos/finalize_photos.py (13 Nov 2026). Do not edit by hand:",
         "// change scripts/photos/picks.json and run it again.",
         "//",
         "// The real photos behind the advisory, calendar and treatment steps (they replaced the cartoon",
         "// scenes; Ezra, 13 Nov: \"real images, not cartoons\"). Every photo is from Wikimedia Commons under",
         "// CC0, public domain, CC BY or CC BY-SA (never NC or ND), cropped to 3:2 and resized. The credit",
         "// shows in the photo's corner and on the How Tassel works screen. To use your own photo: put it",
         "// in assets/story/<kind>.jpg and change its entry in picks.json (author: you, licence: your choice).",
         "import type { SceneKind } from './storyScene';",
         "",
         "export type PhotoCredit = { title: string; author: string; licence: string; licenceUrl: string; source: string; alt: { en: string; sw: string } };",
         "",
         "export const STORY_PHOTO_CREDITS: Record<SceneKind, PhotoCredit> = {"]
for kind in KINDS:
    c = credits[kind]
    lines += [f"  {kind}: {{",
              f"    title: {q(c['title'])},",
              f"    author: {q(c['author'])},",
              f"    licence: {q(c['licence'])},",
              f"    licenceUrl: {q(c['licence_url'])},",
              f"    source: {q(c['source'])},",
              f"    alt: {{ en: {q(c['alt_en'])}, sw: {q(c['alt_sw'])} }},",
              "  },"]
lines += ["};", "",
          "/** The short credit shown in the photo's corner. */",
          "export function creditLine(c: PhotoCredit): string {",
          "  return `${c.author} · ${c.licence}`;",
          "}", ""]
(ROOT / "lib" / "storyPhotos.ts").write_text("\n".join(lines), encoding="utf-8")

md_lines = ["# Story photo credits", "", "Generated by `scripts/photos/finalize_photos.py`. All from Wikimedia Commons; cropped to 3:2 and resized to 960 x 640.", "",
            "| Step | Photo | Author | Licence | Note |", "|---|---|---|---|---|"]
for kind in KINDS:
    c = credits[kind]
    md_lines.append(f"| {kind} | [{c['title']}]({c['source']}) | {c['author']} | [{c['licence']}]({c['licence_url']}) | {c['restrictions']} |")
(ROOT / "scripts" / "photos" / "PHOTO_CREDITS.md").write_text("\n".join(md_lines) + "\n", encoding="utf-8")

sheet = Image.new("RGB", (3 * 330, 6 * 250), "white")
d = ImageDraw.Draw(sheet)
for i, (kind, crop) in enumerate(crops):
    t = crop.copy()
    t.thumbnail((320, 214))
    x, y = (i % 3) * 330 + 5, (i // 3) * 250 + 5
    sheet.paste(t, (x, y))
    d.text((x, y + 218), f"{kind}: {credits[kind]['licence']}", fill="black")
sheet.save(ROOT / "scripts" / "photos" / "final_sheet.jpg", quality=85)
print("DONE", sum((out_dir / f"{k}.jpg").stat().st_size for k in KINDS) // 1024, "KB in total")
