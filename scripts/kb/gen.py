"""Emit lib/diseases.v5.ts and lib/diseases.v5.sw.ts from the kb_* files and validate them.
Usage (from the app root): python3 scripts/kb/gen.py lib"""
import json, re, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent))
import common, kb_a_staples, kb_b_cash, kb_c_cereals, kb_d_veg  # noqa: F401  (registers entries)

OUT = Path(sys.argv[1])
LABELS = list(json.load(open(OUT.parent / 'assets' / 'model' / 'class_labels.json', encoding='utf-8')).values())

SW_ACTIVE = {
    'No effective spray': 'Hakuna dawa yenye ufanisi',
    'No practical spray': 'Hakuna dawa ya kunyunyizia inayofaa',
    'No routine spray': 'Hakuna haja ya kunyunyizia kwa kawaida',
    'No spray cures CBSD': 'Hakuna dawa inayoponya CBSD',
    'No spray cures Fusarium wilt': 'Hakuna dawa inayoponya mnyauko wa Fusarium',
    'No spray cures MLN': 'Hakuna dawa inayoponya MLN',
    'No spray cures bacterial wilt': 'Hakuna dawa inayoponya mnyauko bakteria',
    'No spray cures banana bract mosaic': 'Hakuna dawa inayoponya mosaiki ya brakti ya ndizi',
    'No spray cures cassava mosaic': 'Hakuna dawa inayoponya mosaiki ya muhogo',
    'No spray cures leaf curl': 'Hakuna dawa inayoponya kukunjamana kwa majani',
    'No spray cures little leaf': 'Hakuna dawa inayoponya ugonjwa wa majani madogo',
    'No spray cures maize streak': 'Hakuna dawa inayoponya michirizi ya mahindi',
    'No spray cures mosaic': 'Hakuna dawa inayoponya mosaiki',
    'No spray cures the virus': 'Hakuna dawa inayoponya virusi',
    'No spray cures tungro': 'Hakuna dawa inayoponya tungro',
    'No spray cures wilt': 'Hakuna dawa inayoponya mnyauko',
    'No spray cures yellow leaf': 'Hakuna dawa inayoponya majani ya manjano',
    'Tebuconazole seed treatment': 'Tebuconazole (kutibu mbegu)',
    'Horticultural mineral oil': 'Mafuta ya madini ya bustani (horticultural mineral oil)',
}
COPPER_EN = 'Copper (copper hydroxide or copper oxychloride)'
COPPER_SW = 'Shaba (copper hydroxide au copper oxychloride)'
BANNED = ['chlorothalonil', 'chlorpyrifos', 'dimethoate', 'imidacloprid', 'abamectin', 'iprodione', 'carbofuran']
DOSE = re.compile(r'\d+(\.\d+)?\s*(ml|mls|g|gm|grams?|kg|l|litres?|liters?|%|cc|ppm)\b', re.I)


def q(s):
    if s is None:
        return 'null'
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'") + "'"


def arr(items, ind):
    if not items:
        return '[]'
    if sum(len(i) for i in items) < 70:
        return '[' + ', '.join(q(i) for i in items) + ']'
    pad = ' ' * ind
    return '[\n' + ''.join(f'{pad}  {q(i)},\n' for i in items) + pad + ']'


def chem(items, lang):
    out = []
    for c in items:
        if c == 'COPPER':
            out.append('COPPER')
        elif c == 'MANCOZEB':
            out.append('MANCOZEB')
        elif c[0] == 'COPPER_NOTE':
            note = c[1] if lang == 'en' else c[2]
            out.append(f'{{ active: COPPER.active, note: {q(note)} }}')
        else:
            active = c[0] if lang == 'en' else SW_ACTIVE.get(c[0], c[0])
            if len(c) == 1:
                out.append(f'{{ active: {q(active)} }}')
            else:
                note = c[1] if lang == 'en' else c[2]
                out.append(f'{{ active: {q(active)}, note: {q(note)} }}')
    if not out:
        return '[]'
    one = '[' + ', '.join(out) + ']'
    if len(one) < 90:
        return one
    return '[\n' + ''.join(f'      {o},\n' for o in out) + '    ]'


HEADER = """// GENERATED by scripts/kb/gen.py — the {n} classes the v5 model added
// ({crops} crops). Same v2.0 rules as diseases.ts: cultural, biological and
// chemical options; active ingredients only, never doses; PCPB June 2025
// restrictions respected (no chlorothalonil, chlorpyrifos, dimethoate,
// imidacloprid, abamectin, iprodione or carbofuran); mancozeb carries the
// under-review note. Edit the kb_*.py sources and regenerate, not this file.
"""


def main():
    E = common.ENTRIES
    errors = []
    by_label = {}
    for e in E:
        if e['label'] in by_label:
            errors.append(f"duplicate {e['label']}")
        by_label[e['label']] = e
    en_src = (OUT / 'diseases.ts').read_text(encoding='utf-8')
    old = set(re.findall(r"label: '([^']+)'", en_src)) | set(re.findall(r"healthy\('([^']+)'", en_src))
    need = [l for l in LABELS if l not in old]
    missing = [l for l in need if l not in by_label]
    extra = [l for l in by_label if l not in need]
    if missing:
        errors.append(f'missing guides: {missing}')
    if extra:
        errors.append(f'guides for labels not in the model (or already in diseases.ts): {extra}')

    # Text checks over everything a farmer will read.
    for e in E:
        texts = []
        if e.get('healthy'):
            texts = e['en_tips'] + e['sw_tips']
        else:
            for side in ('en', 'sw'):
                t = e[side]
                texts += [t['disease'], t['symptoms'], t['spread'] or '', t['kenya'] or ''] + t['cultural'] + t['biological']
                if len(t['cultural']) < 1:
                    errors.append(f"{e['label']} {side}: no cultural steps")
            for c in e['chem']:
                if isinstance(c, tuple):
                    texts += list(c)
                    if len(c) not in (1, 3):
                        errors.append(f"{e['label']}: chemical tuple must have 1 or 3 items: {c}")
                    if c[0] not in SW_ACTIVE and c[0][0].islower():
                        errors.append(f"{e['label']}: odd active {c[0]}")
                    if c[0].lower().startswith('no ') and c[0] not in SW_ACTIVE:
                        errors.append(f"{e['label']}: no Swahili for '{c[0]}'")
            if len(e['en']['cultural']) != len(e['sw']['cultural']) or len(e['en']['biological']) != len(e['sw']['biological']):
                errors.append(f"{e['label']}: EN/SW step counts differ")
            if (e['en']['spread'] is None) != (e['sw']['spread'] is None) or (e['en']['kenya'] is None) != (e['sw']['kenya'] is None):
                errors.append(f"{e['label']}: EN/SW null fields differ")
            if e['urgency'] not in ('low', 'medium', 'high', 'critical'):
                errors.append(f"{e['label']}: urgency {e['urgency']}")
            if e['kind'] not in ('Fungal', 'Oomycete', 'Bacterial', 'Viral', 'Pest', 'Algal'):
                errors.append(f"{e['label']}: kind {e['kind']}")
        if e.get('healthy') and len(e['en_tips']) != len(e['sw_tips']):
            errors.append(f"{e['label']}: healthy tip counts differ")
        blob = ' '.join(texts)
        for b in BANNED:
            if b in blob.lower():
                errors.append(f"{e['label']}: mentions restricted active {b}")
        m = DOSE.search(blob)
        if m:
            errors.append(f"{e['label']}: looks like a dose: {m.group(0)!r}")
        if not e['label'].startswith(e['crop'].replace(' ', '_')) and e['crop'] not in ('Beans', 'Citrus', 'Maize'):
            errors.append(f"{e['label']}: crop key {e['crop']} doesn't match label")

    if errors:
        print('\n'.join(errors))
        sys.exit(1)

    order = {l: i for i, l in enumerate(LABELS)}
    E = sorted(E, key=lambda e: order[e['label']])
    crops = sorted({e['crop'] for e in E})

    # ── English ──
    en = [HEADER.format(n=len(E), crops=len(crops)),
          "import type { Chemical, DiseaseInfo } from './diseases';\n",
          "const MANCOZEB_NOTE = 'Mancozeb was under PCPB review in 2025 — confirm the product is still registered.';",
          f"const COPPER: Chemical = {{ active: {q(COPPER_EN)} }};",
          "const MANCOZEB: Chemical = { active: 'Mancozeb', note: MANCOZEB_NOTE };\n",
          "function healthy(label: string, crop: string, tips: string[]): DiseaseInfo {",
          "  return {",
          "    label, crop, disease: 'Healthy', kind: 'Healthy', pathogen: null,",
          "    symptoms: 'No disease symptoms were detected on this leaf.',",
          "    spread: null, urgency: 'low', kenya: null, cultural: tips, biological: [], chemical: [],",
          "  };",
          "}\n",
          "export const V5_LIST: DiseaseInfo[] = ["]
    last = None
    for e in E:
        if e['crop'] != last:
            en.append(f"  // ───────────── {e['crop']} ─────────────")
            last = e['crop']
        if e.get('healthy'):
            en.append(f"  healthy({q(e['label'])}, {q(e['crop'])}, {arr(e['en_tips'], 2)}),")
            continue
        t = e['en']
        lines = ['  {',
                 f"    label: {q(e['label'])},",
                 f"    crop: {q(e['crop'])},",
                 f"    disease: {q(t['disease'])},",
                 f"    kind: {q(e['kind'])},",
                 f"    pathogen: {q(e['pathogen'])},",
                 f"    symptoms: {q(t['symptoms'])},",
                 f"    spread: {q(t['spread'])},",
                 f"    urgency: {q(e['urgency'])},",
                 f"    kenya: {q(t['kenya'])},",
                 f"    cultural: {arr(t['cultural'], 4)},",
                 f"    biological: {arr(t['biological'], 4)},",
                 f"    chemical: {chem(e['chem'], 'en')},"]
        if e.get('notifiable'):
            lines.append('    notifiable: true,')
        lines.append('  },')
        en += lines
    en.append('];\n')
    (OUT / 'diseases.v5.ts').write_text('\n'.join(en), encoding='utf-8')

    # ── Kiswahili ──
    sw = [HEADER.format(n=len(E), crops=len(crops)).replace('// GENERATED', '// Kiswahili — GENERATED'),
          "import type { Chemical } from './diseases';",
          "import type { DiseaseSw } from './diseases.sw';\n",
          "const MANCOZEB_NOTE_SW = 'Mancozeb ilikuwa ikikaguliwa na PCPB mwaka 2025 — hakikisha bidhaa bado imesajiliwa.';",
          f"const COPPER: Chemical = {{ active: {q(COPPER_SW)} }};",
          "const MANCOZEB: Chemical = { active: 'Mancozeb', note: MANCOZEB_NOTE_SW };\n",
          "function healthy(tips: string[]): DiseaseSw {",
          "  return {",
          "    disease: 'Afya',",
          "    symptoms: 'Hakuna dalili za ugonjwa zilizoonekana kwenye jani hili.',",
          "    spread: null, kenya: null, cultural: tips, biological: [], chemical: [],",
          "  };",
          "}\n",
          "export const SW_DISEASES_V5: Record<string, DiseaseSw> = {"]
    for e in E:
        key = e['label'] if re.fullmatch(r'[A-Za-z_]\w*', e['label']) else q(e['label'])
        if e.get('healthy'):
            sw.append(f"  {key}: healthy({arr(e['sw_tips'], 2)}),")
            continue
        t = e['sw']
        lines = [f'  {key}: {{', f"    disease: {q(t['disease'])},"]
        if t.get('pathogen'):
            lines.append(f"    pathogen: {q(t['pathogen'])},")
        lines += [f"    symptoms: {q(t['symptoms'])},",
                  f"    spread: {q(t['spread'])},",
                  f"    kenya: {q(t['kenya'])},",
                  f"    cultural: {arr(t['cultural'], 4)},",
                  f"    biological: {arr(t['biological'], 4)},",
                  f"    chemical: {chem(e['chem'], 'sw')},",
                  '  },']
        sw += lines
    sw.append('};\n')
    (OUT / 'diseases.v5.sw.ts').write_text('\n'.join(sw), encoding='utf-8')
    print(f'OK: {len(E)} guides ({sum(1 for e in E if e.get("healthy"))} healthy), {len(crops)} crops: {", ".join(crops)}')
    print(f'notifiable: {[e["label"] for e in E if e.get("notifiable")]}')


main()
